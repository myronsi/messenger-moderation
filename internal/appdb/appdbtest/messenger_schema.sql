CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             TEXT        NOT NULL,
    display_name         TEXT        NOT NULL,
    password_hash        TEXT        NOT NULL DEFAULT 'hash',
    avatar_url           TEXT,
    bio                  TEXT,
    avatar_attachment_id UUID,
    last_seen_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX users_username_lower_key ON users (LOWER(username));

CREATE TABLE user_reports (
    reporter_id  BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    target_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    reason       TEXT         NOT NULL CHECK (reason IN ('spam', 'scam', 'harassment', 'impersonation', 'inappropriate_profile', 'other')),
    note         TEXT         CHECK (char_length(note) <= 500),
    context      TEXT         NOT NULL CHECK (context IN ('target_initiated', 'shared_chat', 'none')),
    weight       NUMERIC(3,2) NOT NULL CHECK (weight >= 0 AND weight <= 1),
    snapshot     JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    withdrawn_at TIMESTAMPTZ,
    dismissed_at TIMESTAMPTZ,
    PRIMARY KEY (reporter_id, target_id),
    CHECK (reporter_id <> target_id)
);

CREATE INDEX user_reports_target_idx ON user_reports (target_id, created_at);

CREATE TABLE user_moderation (
    user_id              BIGINT        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    status               TEXT          NOT NULL DEFAULT 'good' CHECK (status IN ('good', 'warned', 'limited', 'restricted', 'suspended')),
    score                NUMERIC(12,2) NOT NULL DEFAULT 0,
    status_since         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    probation_until      TIMESTAMPTZ,
    appeal_blocked_until TIMESTAMPTZ,
    last_appeal_at       TIMESTAMPTZ,
    decided_by           TEXT          NOT NULL DEFAULT 'automatic',
    decided_at           TIMESTAMPTZ,
    reason_code          TEXT,
    reason_text          TEXT
);

CREATE TABLE user_moderation_events (
    id          BIGSERIAL     PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    from_status TEXT          NOT NULL,
    to_status   TEXT          NOT NULL,
    score       NUMERIC(12,2) NOT NULL,
    cause       TEXT          NOT NULL,
    reason_code TEXT,
    reason_text TEXT,
    staff_ref   TEXT,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX user_moderation_events_user_idx ON user_moderation_events (user_id, created_at);

CREATE TABLE sticker_packs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    builtin_key TEXT UNIQUE,
    title       TEXT        NOT NULL,
    slug        TEXT UNIQUE,
    hidden_at   TIMESTAMPTZ,
    hidden_by   TEXT CHECK (hidden_by IN ('reports', 'staff')),
    deleted_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE stickers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pack_id       BIGINT      NOT NULL REFERENCES sticker_packs (id) ON DELETE CASCADE,
    attachment_id UUID        NOT NULL,
    emoji         TEXT        NOT NULL,
    position      INTEGER     NOT NULL,
    is_animated   BOOLEAN     NOT NULL DEFAULT false,
    deleted_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE sticker_pack_reports (
    pack_id     BIGINT      NOT NULL REFERENCES sticker_packs (id) ON DELETE CASCADE,
    reporter_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    reason      TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (pack_id, reporter_id)
);

CREATE TABLE emoji_packs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    chat_id    BIGINT UNIQUE,
    title      TEXT        NOT NULL,
    slug       TEXT UNIQUE,
    hidden_at  TIMESTAMPTZ,
    hidden_by  TEXT CHECK (hidden_by IN ('reports', 'staff')),
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE custom_emoji (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pack_id       BIGINT      NOT NULL REFERENCES emoji_packs (id) ON DELETE CASCADE,
    attachment_id UUID        NOT NULL,
    shortcode     TEXT        NOT NULL,
    is_animated   BOOLEAN     NOT NULL DEFAULT false,
    position      INTEGER     NOT NULL,
    deleted_at    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE emoji_pack_reports (
    pack_id     BIGINT      NOT NULL REFERENCES emoji_packs (id) ON DELETE CASCADE,
    reporter_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    reason      TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (pack_id, reporter_id)
);
